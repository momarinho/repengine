import 'dart:convert';
import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:drift/native.dart';

import 'package:repengine_mobile/core/database/app_database.dart';
import 'package:repengine_mobile/core/database/database_provider.dart';
import 'package:repengine_mobile/features/workout_execution/domain/routine_model.dart';
import 'package:repengine_mobile/features/workout_execution/presentation/widgets/routine_import_sheet.dart';

void main() {
  group('CanonicalRoutineImport Unit Tests', () {
    test('parses official RepEngine Web Studio routine format', () {
      final jsonStr = jsonEncode({
        'schema_version': 1,
        'name': 'Upper Lower Hypertrophy',
        'description': '4-day split with double progression accessories',
        'sections': [
          {
            'title': 'Upper Body A',
            'subtitle': 'Chest & Back Focus',
            'blocks': [
              {
                'node_type_slug': 'exercise',
                'exercise_name': 'Barbell Bench Press',
                'sets': 3,
                'reps': '5',
                'target_load': 80.0,
                'rest_seconds': 180,
                'progression': {
                  'type': 'linear',
                  'increment': 2.5,
                },
              },
              {
                'node_type_slug': 'exercise',
                'exercise_name': 'Incline Dumbbell Curl',
                'sets': 3,
                'reps': '8-12',
                'target_load': 14.0,
                'rest_seconds': 90,
                'progression': {
                  'type': 'double',
                  'increment': 1.0,
                  'min_reps': 8,
                  'max_reps': 12,
                },
              },
            ],
          },
        ],
      });

      final imported = CanonicalRoutineImport.parse(jsonStr);

      expect(imported.name, equals('Upper Lower Hypertrophy'));
      expect(imported.description, equals('4-day split with double progression accessories'));
      expect(imported.sections, hasLength(1));

      final section = imported.sections.first;
      expect(section.title, equals('Upper Body A'));
      expect(section.exercises, hasLength(2));

      final bench = section.exercises[0];
      expect(bench.name, equals('Barbell Bench Press'));
      expect(bench.targetLoad, equals(80.0));
      expect(bench.progressionType, equals('linear'));
      expect(bench.progressionIncrement, equals(2.5));

      final curl = section.exercises[1];
      expect(curl.name, equals('Incline Dumbbell Curl'));
      expect(curl.progressionType, equals('double'));
      expect(curl.progressionIncrement, equals(1.0));
      expect(curl.progressionMinReps, equals(8));
      expect(curl.progressionMaxReps, equals(12));
    });

    test('parses AI assistant prompt output with days and exercises keys', () {
      final jsonStr = jsonEncode({
        'name': 'AI Full Body 3x',
        'description': 'Generated by AI coach',
        'days': [
          {
            'title': 'Day 1 - Push Focus',
            'exercises': [
              {
                'name': 'Overhead Press',
                'sets': 4,
                'reps': '6',
                'start_load': 45.0,
                'rest_seconds': 120,
                'progression': {
                  'type': 'linear',
                  'increment': 1.25,
                },
              },
            ],
          },
        ],
      });

      final imported = CanonicalRoutineImport.parse(jsonStr);

      expect(imported.name, equals('AI Full Body 3x'));
      expect(imported.sections, hasLength(1));
      final ex = imported.sections.first.exercises.first;
      expect(ex.name, equals('Overhead Press'));
      expect(ex.targetLoad, equals(45.0));
      expect(ex.progressionIncrement, equals(1.25));
    });

    test('throws FormatException on empty or invalid JSON', () {
      expect(() => CanonicalRoutineImport.parse(''), throwsFormatException);
      expect(() => CanonicalRoutineImport.parse('   '), throwsFormatException);
      expect(() => CanonicalRoutineImport.parse('[]'), throwsFormatException);
      expect(() => CanonicalRoutineImport.parse('{"name": "No sections"}'), throwsFormatException);
    });
  });

  group('RoutineImportSheet Widget Tests', () {
    late AppDatabase db;

    setUp(() {
      db = AppDatabase.forTesting(NativeDatabase.memory());
    });

    tearDown(() async {
      await db.close();
    });

    testWidgets('renders RoutineImportSheet and previews valid routine upon entering JSON', (tester) async {
      final container = ProviderContainer(
        overrides: [
          appDatabaseProvider.overrideWithValue(db),
        ],
      );
      addTearDown(container.dispose);

      await tester.pumpWidget(
        UncontrolledProviderScope(
          container: container,
          child: const MaterialApp(
            home: Scaffold(
              body: RoutineImportSheet(),
            ),
          ),
        ),
      );

      // Verify initial UI elements
      expect(find.text('Paste routine JSON from Web Studio or AI prompts.'), findsOneWidget);
      expect(find.byKey(const Key('paste_clipboard_btn')), findsOneWidget);
      expect(find.byKey(const Key('json_input_field')), findsOneWidget);

      // Confirm import button should be disabled when empty
      final confirmBtn = tester.widget<FilledButton>(find.byKey(const Key('confirm_import_btn')));
      expect(confirmBtn.onPressed, isNull);

      // Enter valid JSON
      final validJson = jsonEncode({
        'name': 'Test Powerlifting Routine',
        'sections': [
          {
            'title': 'Squat Focus',
            'blocks': [
              {
                'exercise_name': 'Competition Squat',
                'sets': 5,
                'reps': '3',
                'target_load': 140.0,
                'progression': {
                  'type': 'linear',
                  'increment': 5.0,
                },
              },
            ],
          },
        ],
      });

      await tester.enterText(find.byKey(const Key('json_input_field')), validJson);
      await tester.pumpAndSettle();

      // Preview card should now be displayed
      expect(find.text('Test Powerlifting Routine'), findsOneWidget);
      expect(find.text('1 Days'), findsOneWidget);
      expect(find.text('1 Exercises'), findsOneWidget);
      expect(find.textContaining('Competition Squat (5x3 @ 140.0kg) • +5.0kg'), findsOneWidget);

      // Confirm import button should now be enabled
      final enabledBtn = tester.widget<FilledButton>(find.byKey(const Key('confirm_import_btn')));
      expect(enabledBtn.onPressed, isNotNull);

      // Tap confirm import
      await tester.tap(find.byKey(const Key('confirm_import_btn')));
      await tester.pumpAndSettle();

      // Check SQLite database to ensure routine was saved
      final routines = await db.select(db.routinesTable).get();
      expect(routines, hasLength(1));
      expect(routines.first.name, equals('Test Powerlifting Routine'));
    });
  });
}
