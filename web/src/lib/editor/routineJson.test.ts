test('parseAndValidateRoutineJson ensures linear_progression has start_load and NO progression field', () => {
	const json = JSON.stringify({
		name: 'Linear Workout',
		sections: [
			{
				title: 'Day 1',
				blocks: [
					{
						type: 'exercise',
						exercise_name: 'Bench Press',
						sets: 3,
						reps: '5',
						target_load: 80,
						progression: {
							type: 'linear',
							increment: 2.5
						}
					}
				]
			}
		]
	});

	const result = parseAndValidateRoutineJson(json);
	assert.equal(result.success, true);
	const exBlock = result.draftBlocks?.[1];
	assert.ok(exBlock);
	assert.equal(exBlock.node_type_slug, 'linear_progression');
	assert.equal(exBlock.data.start_load, 80);
	assert.equal(exBlock.data.increment, 2.5);
	assert.equal(exBlock.data.progression, undefined);
});
