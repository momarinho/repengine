import test from 'node:test';
import assert from 'node:assert/strict';
import {
	exportWorkflowToCanonicalJson,
	parseAndValidateRoutineJson,
	generateAiPromptTemplate,
	type CanonicalRoutineJson
} from './routineJson.ts';
import type { DraftBlock } from './types.ts';

test('exportWorkflowToCanonicalJson formats sections and exercise blocks properly', () => {
	const blocks: DraftBlock[] = [
		{
			client_id: 'sec-1',
			node_type_slug: 'section',
			position: 0,
			data: { title: 'Day 1 - Chest & Shoulders', subtitle: 'Push Focus' }
		},
		{
			client_id: 'ex-1',
			node_type_slug: 'exercise',
			position: 1,
			data: {
				exercise_name: 'Bench Press',
				sets: 3,
				reps: '5',
				load_value: 80,
				load_unit: 'kg',
				rest_seconds: 180,
				notes: 'Pause 1s',
				progression: {
					type: 'linear',
					increment: 2.5,
					rule: 'add_each_session'
				}
			}
		},
		{
			client_id: 'sec-2',
			node_type_slug: 'section',
			position: 2,
			data: { title: 'Day 2 - Legs', subtitle: 'Squat Focus' }
		},
		{
			client_id: 'ex-2',
			node_type_slug: 'linear_progression',
			position: 3,
			data: {
				exercise_name: 'Squat',
				sets: 3,
				reps: '5',
				start_load: 100,
				load_unit: 'kg',
				increment: 5,
				progression_rule: 'add_each_session'
			}
		}
	];

	const canonical = exportWorkflowToCanonicalJson(
		{ name: 'Strength Test', description: 'Power Routine' },
		blocks
	);

	assert.equal(canonical.name, 'Strength Test');
	assert.equal(canonical.sections.length, 2);
	assert.equal(canonical.sections[0].title, 'Day 1 - Chest & Shoulders');
	assert.equal(canonical.sections[0].blocks[0].exercise_name, 'Bench Press');
	assert.equal(canonical.sections[0].blocks[0].target_load, 80);
	assert.equal(canonical.sections[0].blocks[0].progression?.type, 'linear');
	assert.equal(canonical.sections[0].blocks[0].progression?.increment, 2.5);

	assert.equal(canonical.sections[1].title, 'Day 2 - Legs');
	assert.equal(canonical.sections[1].blocks[0].exercise_name, 'Squat');
	assert.equal(canonical.sections[1].blocks[0].target_load, 100);
	assert.equal(canonical.sections[1].blocks[0].progression?.type, 'linear');
	assert.equal(canonical.sections[1].blocks[0].progression?.increment, 5);
});

test('parseAndValidateRoutineJson successfully parses canonical format and produces draft blocks', () => {
	const rawJson = JSON.stringify({
		name: 'PPL Routine',
		description: 'Push Pull Legs',
		sections: [
			{
				title: 'Push Day',
				blocks: [
					{
						type: 'exercise',
						exercise_name: 'Overhead Press',
						sets: 4,
						reps: '6-8',
						target_load: 50,
						load_unit: 'kg',
						rest_seconds: 120,
						progression: {
							type: 'double',
							min_reps: 6,
							max_reps: 8,
							increment: 2.5
						}
					}
				]
			}
		]
	});

	const result = parseAndValidateRoutineJson(rawJson);
	assert.equal(result.success, true);
	assert.ok(result.summary);
	assert.equal(result.summary.name, 'PPL Routine');
	assert.equal(result.summary.sectionsCount, 1);
	assert.equal(result.summary.exercisesCount, 1);
	assert.equal(result.draftBlocks?.length, 2); // 1 section + 1 exercise

	const [sectionBlock, exBlock] = result.draftBlocks!;
	assert.equal(sectionBlock.node_type_slug, 'section');
	assert.equal(sectionBlock.data.title, 'Push Day');

	assert.equal(exBlock.node_type_slug, 'exercise');
	assert.equal(exBlock.data.exercise_name, 'Overhead Press');
	assert.equal(exBlock.data.sets, 4);
	assert.equal(exBlock.data.load_value, 50);
	assert.equal((exBlock.data.progression as any)?.type, 'double');
});

test('parseAndValidateRoutineJson supports AI output format with days and exercises', () => {
	const aiJson = JSON.stringify({
		routine_name: 'AI Hypertrophy 4-Day',
		description: 'Generated by Genkit',
		days: [
			{
				title: 'Upper Day 1',
				exercises: [
					{
						exercise_name: 'Incline Dumbbell Press',
						sets: 3,
						reps: '10',
						target_load: 28,
						rest_seconds: 90
					}
				]
			}
		]
	});

	const result = parseAndValidateRoutineJson(aiJson);
	assert.equal(result.success, true);
	assert.equal(result.summary?.name, 'AI Hypertrophy 4-Day');
	assert.equal(result.summary?.sectionsCount, 1);
	assert.equal(result.summary?.exercisesCount, 1);
	assert.equal(result.draftBlocks?.[1].data.exercise_name, 'Incline Dumbbell Press');
});

test('parseAndValidateRoutineJson rejects invalid or malformed JSON with friendly error', () => {
	const result = parseAndValidateRoutineJson('{ invalid json');
	assert.equal(result.success, false);
	assert.ok(result.error?.includes('Invalid JSON syntax'));

	const emptyResult = parseAndValidateRoutineJson('');
	assert.equal(emptyResult.success, false);
	assert.equal(emptyResult.error, 'JSON content is empty.');

	const noBlocksResult = parseAndValidateRoutineJson(JSON.stringify({ name: 'Empty' }));
	assert.equal(noBlocksResult.success, false);
	assert.ok(noBlocksResult.error?.includes('must contain either'));
});

